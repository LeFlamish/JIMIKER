class Container {
  final String index;
  final double x, y, angle, width, height;
  final int price;
  final String? user;
  final DateTime? startTime;
  final DateTime? endTime;

  Container({
    required this.index,
    required this.x,
    required this.y,
    required this.angle,
    required this.width,
    required this.user,
    required this.startTime,
    required this.endTime,
    required this.height,
    required this.price,
  });
}
