/// 동의 내용이 바뀌면 올린다. 사용자 문서에 함께 저장해서
/// "이 사람이 몇 번째 약관에 동의했는지" 남긴다. 약관을 고치면 숫자를
/// 올리고, 기존 사용자에게 다시 동의를 받는 화면을 붙이면 된다.
const int termsVersion = 1;

class LegalDocument {
  const LegalDocument({
    required this.id,
    required this.title,
    required this.required,
    required this.body,
  });

  final String id;

  final String title;

  /// 동의하지 않으면 가입할 수 없는 항목인지.
  final bool required;

  final String body;
}

/// 가입 화면에 뜨는 순서대로.
